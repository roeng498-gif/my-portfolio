def normalize_lang(value):
    """يرجّع كود لغة مدعوم أو None"""
    if not value:
        return None
    code = str(value).strip().lower().replace('_', '-')
    if code.startswith('ar'):
        return 'ar'
    if code.startswith('en'):
        return 'en'
    return None


def resolve_lang(accept_language=None, session_lang=None, user_lang=None, default=None):
    """ترتيب الأولوية: جلسة/كويري > لغة الحساب > Accept-Language > الافتراضي"""
    for candidate in (session_lang, user_lang):
        code = normalize_lang(candidate)
        if code:
            return code
    if accept_language:
        for part in str(accept_language).split(','):
            code = normalize_lang(part.split(';')[0])
            if code:
                return code
    return normalize_lang(default) or DEFAULT_LANG


def t(key, lang=DEFAULT_LANG, **kwargs):
    """ترجمة مفتاح. لو المفتاح مش موجود بيرجّع نص واضح بدل ما يرمي استثناء."""
    code = normalize_lang(lang) or DEFAULT_LANG
    text = MESSAGES.get(code, {}).get(key)
    if text is None:
        text = MESSAGES[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def has(key, lang=DEFAULT_LANG):
    return key in MESSAGES.get(normalize_lang(lang) or DEFAULT_LANG, {})
